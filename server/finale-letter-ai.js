export function createLetterWriter({ apiKey, model = 'gpt-5.4-mini', request = fetch }) {
    return async note => {
        if (!apiKey || /^replace-with/i.test(apiKey)) throw new AiError('回憶已保存，AI 回信尚未設定；稍後仍可回來領取。');
        try {
            const response = await request('https://api.openai.com/v1/responses', { method: 'POST', headers: { Authorization: 'Bearer ' + apiKey, 'Content-Type': 'application/json' }, body: JSON.stringify({ model, store: false, instructions: LETTER_PROMPT, input: JSON.stringify({ private_memory: note }), max_output_tokens: 700 }), signal: AbortSignal.timeout(25000) });
            if (!response.ok) throw new Error(); const data = await response.json();
            const reply = data.output?.flatMap(item => item.content ?? []).filter(item => item.type === 'output_text').map(item => item.text).join('').trim();
            if (data.status !== 'completed' || !reply || [...reply].length > 300) throw new Error(); return reply;
        } catch { throw new AiError('回憶已保存，但奶龍的回信還沒寫好，請稍後重試。'); }
    };
}
